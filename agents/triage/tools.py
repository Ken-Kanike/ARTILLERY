"""
Artilery Triage Agent — Tool functions for LangGraph nodes.

Each function is an async tool that integrates with an external service:
- create_jira_ticket: Creates a Jira issue via atlassian-python-api
- create_notion_page: Creates a mirrored Notion page
- send_slack_dm: Sends rich Block Kit DMs via slack-sdk
- publish_ticket_created: Publishes ticket.created event to Kafka
"""

from __future__ import annotations

import logging
from datetime import datetime, timezone
from typing import Any, Optional

from shared.config import get_settings

logger = logging.getLogger("artilery.triage.tools")


async def create_jira_ticket(
    summary: str,
    description: str,
    priority: str,
    assignee_jira_id: str,
    service_name: str,
    bug_id: str,
) -> dict[str, Any]:
    """Create a Jira Bug ticket with pre-filled metadata.

    Returns dict with {ticket_key, ticket_url, ticket_id}.
    """
    settings = get_settings()
    logger.info("TRIAGE | Creating Jira ticket | bug_id=%s | service=%s", bug_id, service_name)

    try:
        from atlassian import Jira
        jira = Jira(
            url=settings.JIRA_URL,
            username=settings.JIRA_USERNAME,
            password=settings.JIRA_API_TOKEN,
        )

        full_description = (
            f"*Bug ID:* {bug_id}\n"
            f"*Service:* {service_name}\n"
            f"*Severity:* {priority}\n"
            f"*Timestamp:* {datetime.now(timezone.utc).isoformat()}\n"
            f"*Auto-generated by:* Artilery\n\n"
            f"---\n\n{description}"
        )

        priority_map = {"Critical": "Highest", "High": "High", "Medium": "Medium", "Low": "Low"}

        fields = {
            "project": {"key": settings.JIRA_PROJECT_KEY},
            "summary": summary,
            "description": full_description,
            "issuetype": {"name": "Bug"},
            "priority": {"name": priority_map.get(priority, "Medium")},
            "labels": ["artilery-automated"],
            "assignee": {"accountId": assignee_jira_id},
        }

        result = jira.create_issue(fields=fields)
        ticket_key = result.get("key", "UNKNOWN")
        ticket_id = result.get("id", "")
        ticket_url = f"{settings.JIRA_URL}/browse/{ticket_key}"

        logger.info("TRIAGE | Jira ticket created | key=%s | url=%s", ticket_key, ticket_url)
        return {"ticket_key": ticket_key, "ticket_url": ticket_url, "ticket_id": ticket_id}

    except Exception as exc:
        logger.error("TRIAGE | Jira creation failed | error=%s", exc)
        raise


async def create_notion_page(
    title: str,
    jira_ticket_key: str,
    jira_ticket_url: str,
    service_name: str,
    assignee_name: str,
    priority: str,
    description: str,
) -> dict[str, Any]:
    """Create a Notion page mirroring the Jira ticket.

    Returns dict with {page_id, page_url}.
    """
    settings = get_settings()
    logger.info("TRIAGE | Creating Notion page | jira_key=%s", jira_ticket_key)

    try:
        from notion_client import Client as NotionClient
        notion = NotionClient(auth=settings.NOTION_TOKEN)

        page = notion.pages.create(
            parent={"database_id": settings.NOTION_DATABASE_ID},
            properties={
                "Name": {"title": [{"text": {"content": title}}]},
                "Status": {"select": {"name": "Not Started"}},
                "Priority": {"select": {"name": priority}},
                "Service": {"rich_text": [{"text": {"content": service_name}}]},
                "Jira Link": {"url": jira_ticket_url},
                "Assignee": {"rich_text": [{"text": {"content": assignee_name}}]},
            },
            children=[
                {
                    "object": "block",
                    "type": "paragraph",
                    "paragraph": {
                        "rich_text": [
                            {"type": "text", "text": {"content": f"Linked Jira ticket: {jira_ticket_key} — ", "link": None}},
                            {"type": "text", "text": {"content": jira_ticket_url, "link": {"url": jira_ticket_url}}},
                        ]
                    },
                },
                {
                    "object": "block",
                    "type": "paragraph",
                    "paragraph": {"rich_text": [{"type": "text", "text": {"content": description}}]},
                },
            ],
        )

        page_id = page["id"]
        page_url = page["url"]
        logger.info("TRIAGE | Notion page created | id=%s | url=%s", page_id, page_url)
        return {"page_id": page_id, "page_url": page_url}

    except Exception as exc:
        logger.error("TRIAGE | Notion creation failed | error=%s", exc)
        raise


def _build_severity_blocks(
    bug_summary: str,
    service_name: str,
    priority: str,
    jira_ticket_key: str,
    jira_ticket_url: str,
    notion_page_url: Optional[str] = None,
) -> list[dict[str, Any]]:
    """Build Slack Block Kit blocks for a triage notification."""
    color_map = {"Critical": "🔴", "High": "🟠", "Medium": "🟡", "Low": "🟢"}
    badge = color_map.get(priority, "⚪")

    blocks: list[dict[str, Any]] = [
        {"type": "header", "text": {"type": "plain_text", "text": f"{badge} Bug Assigned — {priority} Priority"}},
        {"type": "section", "text": {"type": "mrkdwn", "text": f"*{bug_summary}*\n\nService: `{service_name}`"}},
        {"type": "divider"},
        {
            "type": "actions",
            "elements": [
                {"type": "button", "text": {"type": "plain_text", "text": f"📋 {jira_ticket_key}"}, "url": jira_ticket_url, "style": "primary"},
            ],
        },
    ]
    if notion_page_url:
        blocks[-1]["elements"].append(
            {"type": "button", "text": {"type": "plain_text", "text": "📝 Notion Page"}, "url": notion_page_url}
        )
    return blocks


async def send_slack_dm(
    slack_user_id: str,
    message: str,
    blocks: Optional[list[dict[str, Any]]] = None,
) -> bool:
    """Send a Slack DM to a user. Uses Block Kit if blocks provided."""
    settings = get_settings()
    logger.info("TRIAGE | Sending Slack DM | user=%s", slack_user_id)

    try:
        from slack_sdk import WebClient
        from slack_sdk.errors import SlackApiError
        client = WebClient(token=settings.SLACK_BOT_TOKEN)

        kwargs: dict[str, Any] = {"channel": slack_user_id, "text": message}
        if blocks:
            kwargs["blocks"] = blocks

        response = client.chat_postMessage(**kwargs)
        logger.info("TRIAGE | Slack DM sent | user=%s | ts=%s", slack_user_id, response.get("ts"))
        return True

    except SlackApiError as exc:
        error_code = exc.response.get("error", "unknown")
        if error_code == "user_not_found":
            logger.warning("TRIAGE | Slack user not found | user=%s", slack_user_id)
        else:
            logger.error("TRIAGE | Slack API error | user=%s | error=%s", slack_user_id, error_code)
        return False
    except Exception as exc:
        logger.error("TRIAGE | Slack DM failed | user=%s | error=%s", slack_user_id, exc)
        return False


async def send_slack_channel_alert(channel_id: str, message: str) -> bool:
    """Send an alert to a Slack channel (used for error escalation)."""
    settings = get_settings()
    try:
        from slack_sdk import WebClient
        client = WebClient(token=settings.SLACK_BOT_TOKEN)
        client.chat_postMessage(channel=channel_id, text=message)
        return True
    except Exception as exc:
        logger.error("TRIAGE | Channel alert failed | channel=%s | error=%s", channel_id, exc)
        return False


async def publish_ticket_created(
    bug_id: str,
    jira_ticket_key: str,
    jira_ticket_url: str,
    notion_page_id: str,
    service_name: str,
    assignee_slack_id: str,
    priority: str,
) -> None:
    """Publish ticket.created event to Kafka."""
    from shared.kafka_utils import KaosProducer

    logger.info("TRIAGE | Publishing ticket.created | bug_id=%s | jira=%s", bug_id, jira_ticket_key)

    payload = {
        "bug_id": bug_id,
        "jira_ticket_key": jira_ticket_key,
        "jira_ticket_url": jira_ticket_url,
        "notion_page_id": notion_page_id,
        "service_name": service_name,
        "assignee_slack_id": assignee_slack_id,
        "priority": priority,
    }

    with KaosProducer() as producer:
        producer.publish(topic="ticket.created", key=bug_id, value=payload)

    logger.info("TRIAGE | ticket.created published | bug_id=%s", bug_id)


